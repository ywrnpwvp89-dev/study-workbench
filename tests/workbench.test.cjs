const assert=require('node:assert/strict');
const w=require('../site/core.js');
assert.deepEqual(w.weeks('1-6单'),[1,3,5]);
assert.deepEqual(w.weeks('1—6双周'),[2,4,6]);
assert.deepEqual(w.weeks('2,4,6'),[2,4,6]);
assert.throws(()=>w.weeks('16-1'));assert.throws(()=>w.weeks('0'));assert.equal(w.weeks(''),null);
const base={name:'虚构课程',credit:2,day:1,start:1,end:2,weeks:'1-16单'};
assert.equal(w.audit([base,{...base,weeks:'1-16双'}]).conflicts.length,0);
assert.equal(w.audit([base,{...base,start:2,end:3,online:true}]).conflicts.length,1);
assert.equal(w.audit([base,{...base,day:2}]).conflicts.length,0);
assert.equal(w.audit([base,{...base,weeks:''}]).conflicts.length,0);
assert(w.audit([base,{...base,weeks:''}]).unknown.some(x=>x.includes('周次')));
assert.equal(w.audit([base,{...base,credit:null}]).total,2);
assert.throws(()=>w.validateCourse({...base,credit:-1}));
assert.throws(()=>w.validateCourse({...base,start:4,end:2}));
assert(w.markdown([base],'课程安排').includes('待确认班号'));
assert.equal(w.audit([{...base,code:'TEST',section:'01'},{...base,code:'TEST',section:'01',day:2}]).total,2);
assert.throws(()=>w.audit([{...base,code:'TEST',section:'01'},{...base,code:'TEST',section:'01',credit:3}]));
console.log('Timetable behavior checks passed, including repeated meetings');
